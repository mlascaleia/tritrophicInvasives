# this script pulls every number the paper reports out of the model objects
# into one md, so nothing reaches the text via console
# this is all in preparation for the great code freeze of 2026

# 07_extractOutputs.R
# For each model: AIC table, summary of the best model, and emmeans / family
# contrasts where the interaction won. Prints everything and writes it to md.

rm(list = ls())
source("analysis/05_makePanTrapModels.R")
source("analysis/00c_branchUseAnalysis.R")

out.file <- "outputs/modelOutputs.md"

# caterpillar models: object suffix -> section title
cat.models <- c(ge    = "Growth efficiency",
                toid  = "Parasitism",
                pupa  = "Unparasitized survival",
                pw    = "Pupal weight",
                death = "Death (all causes)")

# models where the interaction won (get emmeans + family contrasts)
int.models <- c("pupa", "pw", "death")

# models with no AIC table: object name -> section title
field.models <- c(m.tf.wasps = "Pan traps: wasps",
                  m.tf.flies = "Pan traps: flies",
                  m.clay     = "Clay decoys")

supp.models <- c(m.use = "Host use")

# one md section per object: heading, then the printed output in a code block
md_block <- function(title, x) {
  c(paste("###", title), "", "```", capture.output(print(x)), "```", "")
}

outputs <- list()

for (x in names(cat.models)) {
  sec <- list("AICc"       = get(paste0("aic.", x)),
              "Best model" = summary(get(paste0("m.", x))))
  if (x %in% int.models) {
    sec[["emmeans"]]          <- get(paste0("ee.", x))
    sec[["Family contrasts"]] <- summary(get(paste0("gl.", x)),
                                         test = adjusted(type = "none"))
  }
  outputs[[cat.models[[x]]]] <- sec
}

for (x in names(field.models)) {
  outputs[[field.models[[x]]]] <- list("Model" = summary(get(x)))
}

for (x in names(supp.models)) {
  outputs[[supp.models[[x]]]] <- list("Model" = summary(get(x)))
}

md <- c("# Model outputs for Tritrophic Invasive paper", "",
        paste("Generated by 07_extractOutputs.R on", Sys.Date()), "")

for (s in names(outputs)) {
  md <- c(md, paste("##", s), "",
          unlist(Map(md_block, names(outputs[[s]]), outputs[[s]])))
}

cat(md, sep = "\n")       # to console
writeLines(md, out.file)  # to file
